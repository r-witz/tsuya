// Reads tokens/ into flat lists, with the naming helpers every output shares.
//
// tokens/core.json holds what does not change with the mode; tokens/light.json and tokens/dark.json hold the same
// tokens with each mode's values. All three follow the DTCG format ($type, $value, $description); colours are hex.
import { readFileSync } from 'node:fs';

export const ROOT = new URL('..', import.meta.url);
export const read = (path) => readFileSync(new URL(path, ROOT), 'utf8');
export const HEADER = 'Generated by scripts/build.mjs from tokens/. Do not edit: change the JSON and rebuild.';

/** @typedef {{ path: string[], type: string, value: unknown, description: string | undefined }} Token */

// A token is any object with a $value; $type is inherited from the nearest group that sets it.
/** @returns {Token[]} */
function flatten(group, path = [], inheritedType = undefined) {
  const type = group.$type ?? inheritedType;
  return Object.entries(group).flatMap(([key, node]) => {
    if (key.startsWith('$')) return [];
    if ('$value' in node) {
      return [{ path: [...path, key], type: node.$type ?? type, value: node.$value, description: node.$description }];
    }
    return flatten(node, [...path, key], type);
  });
}

export const core = flatten(JSON.parse(read('tokens/core.json')));
export const modes = {
  light: flatten(JSON.parse(read('tokens/light.json'))),
  dark: flatten(JSON.parse(read('tokens/dark.json'))),
};

const byPath = new Map(core.map((t) => [t.path.join('.'), t]));

/** The core token a value such as "{space.16}" points to, or null for a plain value. */
export function referenced(value) {
  if (typeof value !== 'string' || !/^\{[\w.-]+\}$/.test(value)) return null;
  const token = byPath.get(value.slice(1, -1));
  if (!token) throw new Error(`Unknown reference ${value}`);
  return token;
}

/** The value of a token, following references. */
export const valueOf = (token) => (referenced(token.value) ? valueOf(referenced(token.value)) : token.value);

export const group = (tokens, name) => tokens.filter((t) => t.path[0] === name);
export const groupNames = (tokens) => [...new Set(tokens.map((t) => t.path[0]))];
export const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
export const pascal = (name) => camel(name).replace(/^\w/, (c) => c.toUpperCase());
export const memberName = (path) => camel(path.slice(1).join('-'));

// colours drop their group name (--t-bg); every other token keeps it (--t-space-16, --t-accent-tone-min)
export const cssName = (path) => `--t-${(path[0] === 'color' ? path.slice(1) : path).join('-')}`;

// custom properties tokens.css sets besides the tokens: the mode switch and the accent pair
export const RESERVED = ['mode-dark', 'accent-light', 'accent-dark'].map((n) => `--t-${n}`);

/** A font stack as CSS writes it: family names with spaces are quoted. */
export const fontStack = (families) => families.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');

export function parseHex(hex) {
  const n = hex.slice(1);
  const channel = (i) => parseInt(n.slice(i, i + 2), 16);
  return { r: channel(0), g: channel(2), b: channel(4), a: n.length === 8 ? channel(6) / 255 : 1 };
}

/** The tokens of a mode as the colour engine and checkTheme take them: { color, accent, ambient, … }, camelCase. */
export function modeObject(tokens) {
  const out = {};
  for (const t of tokens) (out[t.path[0]] ??= {})[memberName(t.path)] = t.value;
  return out;
}
