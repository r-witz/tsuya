// The static checks that are scripts: raw lengths in component styles, and file length.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, test } from 'vitest';

import { checkLengths, rawLengths } from '../../scripts/lint-lengths.mjs';
import { checkLines } from '../../scripts/lint-lines.mjs';

const work = mkdtempSync(join(tmpdir(), 'tsuya-lint-'));
afterAll(() => {
  rmSync(work, { recursive: true, force: true });
});

describe('raw lengths', () => {
  test('flags lengths, percentages and durations that are not tokens', () => {
    const css = `.a {
      padding: 12px var(--t-space-16);
      margin: -4px 0;
      width: 50%;
      transition: opacity 150ms, transform 0.2s;
      gap: .5rem;
    }`;
    expect(rawLengths(css).map((f) => f.value)).toEqual(['12px', '-4px', '50%', '150ms', '0.2s', '.5rem']);
  });

  test('allows zero, hairlines, 100%, token names, hex colours, comments, and the values of a line that says why', () => {
    const css = `/* was 13px */ .t-icon-24px { margin: 0; border: 1px solid #1e3a5f; width: 100%; top: 0px;
      height: calc(var(--t-space-32) - var(--t-space-4)); }
      .pin { translate: 30% -30%; /* raw: a pin overlaps the corner */ }
      .bar { width: 240px; /* raw: */ }`;
    expect(rawLengths(css).map((f) => f.value)).toEqual(['240px']);
  });

  test('reads the styles of Svelte files: blocks, attributes and directives', () => {
    const lib = join(work, 'lib');
    mkdirSync(join(lib, 'components/sidebar'), { recursive: true });
    const source = [
      '<nav style="width: 999px" style:gap="3px" data-size="17px"></nav>',
      '<style>',
      '  nav {',
      '    width: 240px; /* raw: a sidebar is 240 wide */',
      '    gap: 6px;',
      '  }',
      '</style>',
    ].join('\n');
    writeFileSync(join(lib, 'components/sidebar/Sidebar.svelte'), source);
    const errors = checkLengths(lib);
    expect(errors[0]).toMatch(/say why: \/\* raw: <reason> \*\//);
    expect(errors.map((e) => /raw value (\S+) \(line (\d+)\)/.exec(e)?.slice(1).join('@'))).toEqual([
      '999px@1',
      '3px@1',
      '6px@5',
    ]);
  });
});

describe('file length', () => {
  test('refuses hand-written files over 500 lines, exempts tests and generated files', () => {
    const root = join(work, 'repo');
    mkdirSync(join(root, 'src'), { recursive: true });
    mkdirSync(join(root, 'test'), { recursive: true });
    const lines = (n: number, first = '// x') =>
      [first, ...Array.from({ length: n - 1 }, () => 'x;')].join('\n') + '\n';
    writeFileSync(join(root, 'src/ok.ts'), lines(500));
    writeFileSync(join(root, 'src/long.dart'), lines(501));
    writeFileSync(join(root, 'test/long_test.dart'), lines(900));
    writeFileSync(join(root, 'src/tokens.g.dart'), lines(900, '// Generated by scripts/build.mjs'));
    writeFileSync(join(root, 'src/notes.md'), lines(900));
    expect(checkLines(root)).toEqual(['src/long.dart: 501 lines, more than 500.']);
  });
});
